// Command gencrc extracts the two CRC-16 tables that FSolar uses in its binary
// (0x18/0x19) protocol from the decompiled source and writes them as Go.
//
// Usage: go run ./tools/gencrc decompiled/sources/b/b.java go-fsolar/internal/fsolar/crc_tables.go
package main

import (
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var tableRe = regexp.MustCompile(`(?s)(f6356a|f6357b) = \{(.*?)\};`)

// Java byte literals that jadx left as symbolic constants.
var substitutions = []struct {
	from string
	to   string
}{
	{"ByteCompanionObject.MIN_VALUE", "-128"},
	{"ByteCompanionObject.MAX_VALUE", "127"},
	{"Base64.padSymbol", "61"}, // '='
}

func main() {
	if len(os.Args) < 3 {
		fmt.Fprintln(os.Stderr, "usage: gencrc <b.java> <out.go>")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}

	tables := map[string][]byte{}
	for _, m := range tableRe.FindAllStringSubmatch(string(src), -1) {
		raw := m[2]
		for _, s := range substitutions {
			raw = strings.ReplaceAll(raw, s.from, s.to)
		}
		var vals []byte
		for _, tok := range strings.Split(raw, ",") {
			tok = strings.TrimSpace(tok)
			if tok == "" {
				continue
			}
			n, err := strconv.Atoi(tok)
			if err != nil {
				fmt.Fprintf(os.Stderr, "bad token %q: %v\n", tok, err)
				os.Exit(1)
			}
			vals = append(vals, byte(n))
		}
		// Keep the decompiled field names so there is never any doubt about
		// which table feeds which accumulator.
		name := "crcTableA" // b/b.java field f6356a
		if m[1] == "f6357b" {
			name = "crcTableB" // b/b.java field f6357b
		}
		if len(vals) != 256 {
			fmt.Fprintf(os.Stderr, "%s: expected 256 entries, got %d\n", name, len(vals))
			os.Exit(1)
		}
		tables[name] = vals
	}
	if len(tables) != 2 {
		fmt.Fprintln(os.Stderr, "could not find both tables in", os.Args[1])
		os.Exit(1)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/gencrc from %s. DO NOT EDIT.\n\n", os.Args[1])
	b.WriteString("package fsolar\n\n")
	b.WriteString("// crcTableA is FSolar's b/b.java field f6356a: it updates the accumulator\n")
	b.WriteString("// that ends up as the LOW byte of the checksum.\n")
	b.WriteString("var crcTableA = [256]byte{\n")
	writeTable(&b, tables["crcTableA"])
	b.WriteString("}\n\n")
	b.WriteString("// crcTableB is FSolar's b/b.java field f6357b: it becomes the HIGH byte of\n")
	b.WriteString("// the checksum.\n")
	b.WriteString("var crcTableB = [256]byte{\n")
	writeTable(&b, tables["crcTableB"])
	b.WriteString("}\n")

	if err := os.WriteFile(os.Args[2], []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	fmt.Println("wrote", os.Args[2])
}

func writeTable(b *strings.Builder, t []byte) {
	for i := 0; i < len(t); i += 8 {
		b.WriteString("\t")
		for j := i; j < i+8; j++ {
			if j > i {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "0x%02X", t[j])
		}
		b.WriteString(",\n")
	}
}
