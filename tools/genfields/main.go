// Command genfields turns FSolar's own protocol table into Go source.
//
// The app ships a per-device-type field table (jsonKey, array position,
// decimal magnification and display precision) inside
//   assets/file_config_cache_zip/file_data_protocol_cache/
//       dataProtocol_1516001837143105536_1.0.27.zip
// which unzips to protocol_realtime_1.0.27.json.
//
// Rather than re-typing those rows, this tool reads them so the Go decoder
// uses exactly the app's numbers.
//
// Usage: go run ./tools/genfields <protocol_realtime.json> <type> <out.go>
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strconv"
	"strings"
)

type entry struct {
	BaseParamName string  `json:"baseParamName"`
	ParamName     string  `json:"paramName"`
	Position      string  `json:"position"`
	Magnification int     `json:"magnification"`
	Precisions    int     `json:"precisions"`
	ParamType     int     `json:"paramType"`
	EnumList      *string `json:"enumList"`
}

// labels annotates the app's machine names with readable ones. The names on
// the left are the app's; only the prose on the right is ours.
var labels = map[string][2]string{
	"battVolt":             {"pack voltage", "V"},
	"battCurr":             {"pack current", "A"},
	"battSoc":              {"pack SOC", "%"},
	"battSoh":              {"pack SOH", "%"},
	"battCapacity":         {"pack capacity", "Ah"},
	"emsVoltage":           {"EMS voltage", "V"},
	"emsCurrent":           {"EMS current", "A"},
	"emsSoc":               {"EMS SOC", "%"},
	"emsSoh":               {"EMS SOH", "%"},
	"emsCapacity":          {"EMS capacity", "Ah"},
	"cellNumber":           {"cell count", ""},
	"seriesParallelStatus": {"series/parallel", ""},
	"tempMax":              {"max temp", "C"},
	"tempMin":              {"min temp", "C"},
	"maxCellTempNum":       {"max temp cell index", "#"},
	"minBattTempNum":       {"min temp cell index", "#"},
	"maxVoltage2bms":       {"max cell voltage", "V"},
	"minVoltage2bms":       {"min cell voltage", "V"},
	"maxVoltageNum2bms":    {"max cell index (0-based)", "#"},
	"minVoltageNum2bms":    {"min cell index (0-based)", "#"},
	"BMSLCVolt":            {"charge volt limit", "V"},
	"BMSLDVolt":            {"discharge volt limit", "V"},
	"BMSLCCurr":            {"charge curr limit", "A"},
	"BMSLDCurr":            {"discharge curr limit", "A"},
	"bmsState":             {"BMS state word", ""},
}

// unitOf is only consulted for parameters the table above does not cover; it
// guesses from the name so unusual device types still get something sensible.
func unitOf(name string) string {
	n := strings.ToLower(name)
	switch {
	case strings.Contains(n, "curr"):
		return "A"
	case strings.Contains(n, "volt"):
		return "V"
	case strings.Contains(n, "temp"):
		return "C"
	case strings.Contains(n, "soc"), strings.Contains(n, "soh"):
		return "%"
	case strings.Contains(n, "capacity"):
		return "Ah"
	default:
		return ""
	}
}

// cellName rewrites the app's cellVoltN / cellTempN so generated labels read
// naturally.
func labelOf(name string) (string, string) {
	if l, ok := labels[name]; ok {
		return l[0], l[1]
	}
	for _, prefix := range []string{"cellVolt", "cellTemp"} {
		if strings.HasPrefix(name, prefix) {
			kind := "cell voltage"
			if prefix == "cellTemp" {
				kind = "cell temperature"
			}
			return kind + " " + strings.TrimPrefix(name, prefix), unitOf(name)
		}
	}
	return strings.ToLower(name), unitOf(name)
}

func main() {
	if len(os.Args) < 4 {
		fmt.Fprintln(os.Stderr, "usage: genfields <protocol_realtime.json> <type> <out.go>")
		os.Exit(2)
	}
	typeKey := os.Args[2]

	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	var all map[string]json.RawMessage
	if err := json.Unmarshal(raw, &all); err != nil {
		fmt.Fprintln(os.Stderr, "parse:", err)
		os.Exit(1)
	}
	blob, ok := all[typeKey]
	if !ok {
		fmt.Fprintf(os.Stderr, "device type %q not in protocol table\n", typeKey)
		os.Exit(1)
	}
	var rows []entry
	if err := json.Unmarshal(blob, &rows); err != nil {
		fmt.Fprintf(os.Stderr, "type %q is not a field array: %v\n", typeKey, err)
		os.Exit(1)
	}

	// Keep the app's own declaration order: it groups the headline values
	// first, then the per-cell arrays.
	seen := map[string]bool{}
	var out []entry
	for _, e := range rows {
		key := e.BaseParamName + "|" + e.Position + "|" + e.ParamName
		if seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, e)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/genfields from %s, device type %s.\n", os.Args[1], typeKey)
	fmt.Fprintf(&b, "// Do not edit by hand; regenerate instead.\n\n")
	fmt.Fprintf(&b, "package fsolar\n\n")
	fmt.Fprintf(&b, "// RealtimeFields is the Type=%s mapping used to read the payload of\n", typeKey)
	fmt.Fprintf(&b, "// \"wifilocalMonitor:get dev real infor\".\n")
	fmt.Fprintf(&b, "var RealtimeFields = []Field{\n")
	for _, e := range out {
		outer, inner, hasPos := splitPosition(e.Position)
		if !hasPos {
			// Scalar fields (empty position) still need the alias fix-up, so
			// keep them and read them at index [0][0].
			outer, inner = 0, 0
		}
		label, unit := labelOf(e.ParamName)
		fmt.Fprintf(&b, "\t{%q, %d, %d, %d, %d, %q, %q, %q},\n",
			e.BaseParamName, outer, inner, e.Magnification, e.Precisions,
			e.ParamName, label, unit)
	}
	b.WriteString("}\n")

	if err := os.WriteFile(os.Args[3], []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d fields for type %s)\n", os.Args[3], len(out), typeKey)
}

func splitPosition(p string) (int, int, bool) {
	p = strings.TrimSpace(p)
	if p == "" {
		return 0, 0, false
	}
	parts := strings.Split(p, ",")
	if len(parts) != 2 {
		return 0, 0, false
	}
	outer, err := strconv.Atoi(strings.TrimSpace(parts[0]))
	if err != nil {
		return 0, 0, false
	}
	inner, err := strconv.Atoi(strings.TrimSpace(parts[1]))
	if err != nil {
		return 0, 0, false
	}
	return outer, inner, true
}
